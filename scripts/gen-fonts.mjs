#!/usr/bin/env node
/**
 * Bundles the editorial style's fonts (latin subsets, SIL Open Font License 1.1) as base64
 * @font-face CSS, so renders are hermetic and core stays Workers-safe (no file access).
 * Run: `pnpm gen:fonts` (needs network; output is committed).
 *
 * Fraunces © The Fraunces Project Authors · DM Sans © The DM Sans Project Authors ·
 * Geist Mono © Vercel. All OFL-1.1, via @fontsource on npm.
 */
import { writeFileSync } from "node:fs";

const FONTS = [
  { family: "Fraunces", pkg: "fraunces", file: "fraunces-latin-600-normal", weight: 600, style: "normal" },
  { family: "Fraunces", pkg: "fraunces", file: "fraunces-latin-600-italic", weight: 600, style: "italic" },
  { family: "DM Sans", pkg: "dm-sans", file: "dm-sans-latin-500-normal", weight: 500, style: "normal" },
  { family: "DM Sans", pkg: "dm-sans", file: "dm-sans-latin-700-normal", weight: 700, style: "normal" },
  { family: "Geist Mono", pkg: "geist-mono", file: "geist-mono-latin-500-normal", weight: 500, style: "normal" },
];
const VERSION = "5.3.0";

let css = "";
for (const f of FONTS) {
  const url = `https://cdn.jsdelivr.net/npm/@fontsource/${f.pkg}@${VERSION}/files/${f.file}.woff2`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const b64 = Buffer.from(await res.arrayBuffer()).toString("base64");
  css += `@font-face{font-family:"${f.family}";font-style:${f.style};font-weight:${f.weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2");}`;
}
writeFileSync(
  new URL("../packages/core/src/styles/fonts.generated.ts", import.meta.url),
  `// Generated by scripts/gen-fonts.mjs. Do not edit. Fonts: SIL Open Font License 1.1 (@fontsource ${VERSION}).\nexport const EDITORIAL_FONT_FACES = ${JSON.stringify(css)};\n`,
);
console.log(`fonts: ${FONTS.length} faces, ${Math.round(css.length / 1024)} KB`);
