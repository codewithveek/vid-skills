#!/usr/bin/env node
// Compiles editable Markdown into TS modules so prompts/docs ship inside Workers bundles (no fs at runtime):
//   /prompts/*.md                          -> packages/core/src/prompts.generated.ts
//   docs/audit/*.md, docs/provider-limits.md, skills/*/SKILL.md, agents/*.md -> packages/mcp/src/docs.generated.ts
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const md = (dir) => (existsSync(join(root, dir)) ? readdirSync(join(root, dir)).filter((f) => f.endsWith(".md")).sort() : []);

const prompts = md("prompts").map((f) => [f.replace(/\.md$/, ""), readFileSync(join(root, "prompts", f), "utf8")]);
writeFileSync(
  join(root, "packages/core/src/prompts.generated.ts"),
  `// AUTO-GENERATED by scripts/gen-prompts.mjs from /prompts/*.md. Do not edit.\nexport const PROMPTS = {\n${prompts.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n} as const;\nexport type PromptName = keyof typeof PROMPTS;\n`,
);

const docs = {};
for (const f of md("docs/audit")) docs[`audit/${f.replace(/\.md$/, "")}`] = readFileSync(join(root, "docs/audit", f), "utf8");
if (existsSync(join(root, "docs/provider-limits.md"))) docs["provider-limits"] = readFileSync(join(root, "docs/provider-limits.md"), "utf8");
if (existsSync(join(root, "docs/distribution.md"))) docs["distribution"] = readFileSync(join(root, "docs/distribution.md"), "utf8");
if (existsSync(join(root, "skills"))) {
  for (const d of readdirSync(join(root, "skills")).sort()) {
    const p = join(root, "skills", d, "SKILL.md");
    if (existsSync(p)) docs[`skills/${d}`] = readFileSync(p, "utf8");
  }
}
for (const f of md("agents")) docs[`agents/${f.replace(/\.md$/, "")}`] = readFileSync(join(root, "agents", f), "utf8");
writeFileSync(join(root, "packages/mcp/src/docs.generated.ts"), `// AUTO-GENERATED by scripts/gen-prompts.mjs. Do not edit.\nexport const DOCS: Record<string, string> = ${JSON.stringify(docs, null, 1)};\n`);
console.log(`prompts: ${prompts.length}, docs: ${Object.keys(docs).length}`);
