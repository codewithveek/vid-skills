#!/usr/bin/env node
// Compiles /prompts/*.md into packages/core/src/prompts.generated.ts so the prompts
// ship inside the Workers bundle (no fs at runtime) while staying editable as Markdown.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "prompts");
const entries = readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => [f.replace(/\.md$/, ""), readFileSync(join(dir, f), "utf8")]);
const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const out = `// AUTO-GENERATED by scripts/gen-prompts.mjs from /prompts/*.md. Do not edit.\nexport const PROMPTS = {\n${body}\n} as const;\nexport type PromptName = keyof typeof PROMPTS;\n`;
writeFileSync(join(root, "packages/core/src/prompts.generated.ts"), out);
console.log(`prompts: ${entries.length} compiled`);
