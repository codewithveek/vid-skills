// Bundle Lucide (ISC) as path-only stroke icons for diagram scenes.
// Every primitive becomes a <path d> so the draw-on (pathLength=1 dash) works the same for all icons.
// Output: packages/core/src/hyperframes/icons.lucide.generated.ts (never edit by hand; run `pnpm gen`).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const pkgDir = dirname(require.resolve("lucide-static/package.json"));
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
const dir = join(pkgDir, "icons");

const num = (v) => Number.parseFloat(v ?? "0");
const fmt = (n) => String(Math.round(n * 1000) / 1000);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const ring = (cx, cy, rx, ry) => `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0`;
const points = (p) => p.trim().split(/[\s,]+/).map(Number);

function toPath(tag, a) {
  switch (tag) {
    case "path":
      return a.d;
    case "circle":
      return ring(num(a.cx), num(a.cy), num(a.r), num(a.r));
    case "ellipse":
      return ring(num(a.cx), num(a.cy), num(a.rx), num(a.ry));
    case "line":
      return `M${fmt(num(a.x1))} ${fmt(num(a.y1))}L${fmt(num(a.x2))} ${fmt(num(a.y2))}`;
    case "polyline":
    case "polygon": {
      const p = points(a.points);
      let d = `M${fmt(p[0])} ${fmt(p[1])}`;
      for (let i = 2; i + 1 < p.length; i += 2) d += `L${fmt(p[i])} ${fmt(p[i + 1])}`;
      return tag === "polygon" ? `${d}Z` : d;
    }
    case "rect": {
      const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
      const rx = Math.min(num(a.rx ?? a.ry), w / 2), ry = Math.min(num(a.ry ?? a.rx), h / 2);
      if (!rx) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return `M${fmt(x + rx)} ${fmt(y)}h${fmt(w - 2 * rx)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(ry)}v${fmt(h - 2 * ry)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(ry)}h${fmt(-(w - 2 * rx))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(-ry)}v${fmt(-(h - 2 * ry))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(-ry)}Z`;
    }
    default:
      return null;
  }
}

const out = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(dir, file), "utf8");
  const paths = [];
  for (const m of svg.matchAll(/<(path|circle|ellipse|line|polyline|polygon|rect)\b([^>]*)\/?>/g)) {
    const d = toPath(m[1], attrs(m[2]));
    if (d) paths.push(d);
  }
  if (paths.length) out[file.slice(0, -4)] = paths;
}

const body = `/* Generated by scripts/gen-icons.mjs from lucide-static@${version} (ISC, https://lucide.dev/license). Do not edit. */
// prettier-ignore
export const LUCIDE: Record<string, string[]> = ${JSON.stringify(out)};
`;
writeFileSync(join(root, "packages/core/src/hyperframes/icons.lucide.generated.ts"), body);
console.log(`icons: ${Object.keys(out).length} (lucide ${version})`);
